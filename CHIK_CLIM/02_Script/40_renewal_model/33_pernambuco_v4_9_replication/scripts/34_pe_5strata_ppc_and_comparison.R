stratum_colours <- c("1_Recife" = "#D55E00", "2_Metropolitana_remainder" = "#E69F00",
                      "3_Agreste" = "#009E73", "4_Sertao" = "#0072B2", "5_Vale_Sao_Francisco_Araripe" = "#CC79A7")

summarise_draws <- function(arr2d) { # arr2d: [iter, N]
  tibble(median = apply(arr2d, 2, median), lo95 = apply(arr2d, 2, quantile, .025), hi95 = apply(arr2d, 2, quantile, .975))
}

# ---- Figure: regional observed vs predicted weekly cases + summed state ----
regional_ppc <- bind_rows(lapply(seq_len(R), function(r) {
  s <- summarise_draws(draws$C_pred[, , r])
  s$week_start <- weeks; s$observed <- b$stan_data$C[, r]; s$stratum <- stratum_levels[r]
  s
}))
p_regional_ppc <- ggplot(regional_ppc, aes(week_start)) +
  geom_ribbon(aes(ymin = lo95, ymax = hi95, fill = stratum), alpha = 0.25) +
  geom_line(aes(y = median, colour = stratum), linewidth = 0.3) +
  geom_point(aes(y = observed), colour = "black", size = 0.25, alpha = 0.5) +
  facet_wrap(~stratum, ncol = 1, scales = "free_y") +
  scale_colour_manual(values = stratum_colours, guide = "none") + scale_fill_manual(values = stratum_colours, guide = "none") +
  labs(title = "Pernambuco Spatial Model 1: regional observed vs predicted weekly cases",
       subtitle = "Black points = observed; ribbon = 95% posterior predictive", x = NULL, y = "Weekly cases") +
  theme_v4 + theme(strip.background = element_blank())
ggsave(file.path(figure_dir, "PE_5strata_case_PPC.png"), p_regional_ppc, width = 220, height = 260, units = "mm", dpi = 300, bg = "white")
message("[saved] ", file.path(figure_dir, "PE_5strata_case_PPC.png"))


# ---- Recife U14 serology fit ------------------------------------------------
p_site <- draws$p_site_window[, 1]
obs_prev <- b$stan_data$sero_n_positive[1] / b$stan_data$sero_n_tested[1]
obs_ci <- prop.test(b$stan_data$sero_n_positive[1], b$stan_data$sero_n_tested[1])$conf.int
sero_df <- tibble(source = c("Model (Recife stratum, direct link)", "Observed (U14)"),
                   median = c(median(p_site), obs_prev), lo95 = c(quantile(p_site, .025), obs_ci[1]),
                   hi95 = c(quantile(p_site, .975), obs_ci[2]))
p_sero <- ggplot(sero_df, aes(source, median, colour = source)) +
  geom_point(size = 3) + geom_errorbar(aes(ymin = lo95, ymax = hi95), width = 0.15) +
  scale_colour_manual(values = c("Model (Recife stratum, direct link)" = "#D55E00", "Observed (U14)" = "black"), guide = "none") +
  labs(title = "Recife U14 serology: model (direct Recife-stratum link) vs observed",
       subtitle = "Spatial Model 1 uses NO geographic-offset transport (Section 9) -- Recife IS its own stratum",
       x = NULL, y = "Seroprevalence") + theme_v4 + coord_flip()
ggsave(file.path(figure_dir, "PE_Recife_U14_fit.png"), p_sero, width = 180, height = 90, units = "mm", dpi = 300, bg = "white")
message("[saved] ", file.path(figure_dir, "PE_Recife_U14_fit.png"))
message(sprintf("\nRecife U14 fit: model median=%.4f [%.4f,%.4f] vs observed=%.4f [%.4f,%.4f]",
                 median(p_site), quantile(p_site,.025), quantile(p_site,.975), obs_prev, obs_ci[1], obs_ci[2]))

# ---- Section 18: homogeneous vs spatial comparison table -------------------
homog <- readRDS(file.path(pe_root, "outputs/modelB_U14_full/renewal_pe_global_q_fit_modelB_U14_full.rds"))
homog_fit <- homog$fit
homog_draws <- rstan::extract(homog_fit, permuted = TRUE)
homog_q <- plogis(homog_draws$logit_q)
homog_min_S <- apply(homog_draws$S_prop, 1, min)
homog_max_R0 <- apply(homog_draws$R0_t, 1, max)
homog_immune_2025 <- homog_draws$immune_prop[, ncol(homog_draws$immune_prop)]
homog_cor_q_alpha <- cor(homog_draws$logit_q, homog_draws$alpha_R)
homog_sp <- rstan::get_sampler_params(homog_fit, inc_warmup = FALSE)
homog_divergences <- sum(sapply(homog_sp, function(x) sum(x[, "divergent__"])))
homog_case_ppc_rmse <- sqrt(mean((apply(homog_draws$C_pred, 2, median) - homog$stan_data$C)^2))
homog_u14_pred <- homog_draws$p_site_window[, 1]

spatial_min_S <- apply(draws$S_prop, 1, min)
spatial_max_R0 <- apply(draws$R0_t, 1, max)
spatial_case_ppc_rmse <- sqrt(mean((apply(draws$C_pred, c(2, 3), median) - b$stan_data$C)^2))

comparison <- tibble(
  metric = c("HMC status", "q (median [95% CrI])", "min S/N (any stratum/state)", "immune_2025 (statewide, median)",
             "max R0 (any stratum/state)", "cor(logit_q, alpha)", "case PPC RMSE (per obs)", "U14 fit (model median [95% CrI] vs observed)"),
  homogeneous_model = c(
    if (homog_divergences == 0) "PASS-ish (see model notes)" else sprintf("FAIL (%d divergences)", homog_divergences),
    sprintf("%.4f [%.4f, %.4f]", median(homog_q), quantile(homog_q, .025), quantile(homog_q, .975)),
    sprintf("%.4f", median(homog_min_S)),
    sprintf("%.4f", median(homog_immune_2025)),
    sprintf("%.2f", median(homog_max_R0)),
    sprintf("%.3f", homog_cor_q_alpha),
    sprintf("%.2f", homog_case_ppc_rmse),
    sprintf("%.4f [%.4f, %.4f] vs %.4f", median(homog_u14_pred), quantile(homog_u14_pred, .025), quantile(homog_u14_pred, .975), obs_prev)
  ),
  spatial_5strata_model = c(
    if (b$hmc$hmc_pass) "PASS" else sprintf("FAIL (%d divergences)", b$hmc$divergences),
    sprintf("%.4f [%.4f, %.4f]", median(q_draws <- plogis(draws$logit_q)), quantile(q_draws, .025), quantile(q_draws, .975)),
    sprintf("%.4f", median(spatial_min_S)),
    sprintf("%.4f", median(draws$U_PE_prop[, ncol(draws$U_PE_prop)])),
    sprintf("%.2f", median(spatial_max_R0)),
    sprintf("%.3f", cor(draws$logit_q, draws$alpha_global)),
    sprintf("%.2f", spatial_case_ppc_rmse),
    sprintf("%.4f [%.4f, %.4f] vs %.4f", median(p_site), quantile(p_site, .025), quantile(p_site, .975), obs_prev)
  )
)
message("\n=== Section 18: homogeneous vs spatial comparison ===")
print(as.data.frame(comparison))
write_csv(comparison, file.path(table_dir, "PE_homogeneous_vs_spatial.csv"))
message("[saved] ", file.path(table_dir, "PE_homogeneous_vs_spatial.csv"))


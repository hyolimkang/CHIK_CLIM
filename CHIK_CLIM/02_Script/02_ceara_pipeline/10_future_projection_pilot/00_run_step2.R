# STEP 2 standalone runner -- stochastic future epidemic generator.
#
# Runs mandatory validation FIRST (and stops if it fails), then the
# simulation ensemble, then the figures. No vaccination, no SSP/CMIP6
# forcing -- stationary/resampled historical climate only. Requires
# CHIK_CLIM.Rproj to already be open (or 00_project_setup.R already
# sourced). Pure R simulation throughout -- no Stan fitting/refitting.
#
# Usage:
#   Sys.setenv(FUTURE_PILOT_ENSEMBLE_MODE = "smoke")  # or "pilot" (default "smoke" if unset)
#   source("02_Script/02_ceara_pipeline/10_future_projection_pilot/00_run_step2.R")
#
# Outputs:
#   03_Output/02_ceara_pipeline/tables/future_projection_pilot/STEP2_unit_test_QA_summary.csv
#   03_Output/02_ceara_pipeline/results/future_projection_pilot/STEP2_*.{rds,csv}
#   03_Output/02_ceara_pipeline/figures/future_projection_pilot/FIG05-09.{pdf,png,svg}
#   03_Output/02_ceara_pipeline/reports/future_projection_pilot/STEP2_FUTURE_GENERATOR_ASSESSMENT.md (pre-written; not regenerated by this script)

if (!exists("ROOT")) stop("ROOT not found -- open CHIK_CLIM.Rproj or source CHIK_CLIM/00_project_setup.R first.")
DIR_STEP2 <- file.path(ROOT, "02_Script/02_ceara_pipeline/10_future_projection_pilot")

message("=== STEP 2a: mandatory validation (unit tests) ===")
source(file.path(DIR_STEP2, "04_run_unit_tests.R")) # stops with an error if any check fails

message("\n=== STEP 2b: simulation ensemble (mode=", Sys.getenv("FUTURE_PILOT_ENSEMBLE_MODE", "smoke"), ") ===")
source(file.path(DIR_STEP2, "05_run_simulation_ensemble.R"))

message("\n=== STEP 2c: figures ===")
source(file.path(DIR_STEP2, "06_step2_figures.R"))
message("\n=== STEP 2 complete. See 03_Output/02_ceara_pipeline/reports/future_projection_pilot/STEP2_FUTURE_GENERATOR_ASSESSMENT.md ===")
